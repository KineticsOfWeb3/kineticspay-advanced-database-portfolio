-- =====================================================================
-- KineticsPay - bulk load of the benchmark dataset
-- Portfolio 2: Query Processing and Optimisation
--
-- Run from this directory, AFTER schema.sql and seed.sql:
--     psql -d kineticspay -f load_data.sql
--
-- WHY TRIGGERS ARE DISABLED FOR THE LOAD
-- --------------------------------------
-- Portfolio 1 attached three integrity triggers to ledger_entries and one to
-- transactions. Two of them are DEFERRABLE constraint triggers that run a
-- subquery per row at COMMIT. For 528,630 rows that is 528,630 aggregate
-- queries, which would dominate the load and tell us nothing.
--
-- They are therefore disabled for the COPY and re-enabled immediately after.
-- This is a standard bulk-load technique, but it means the loaded data is
-- UNVALIDATED at that point - so section 5 below re-checks every invariant
-- the triggers would have enforced, against the whole table. Correctness is
-- demonstrated, not assumed.
-- =====================================================================

\timing on

-- ---------------------------------------------------------------------
-- 1. Allow explicit identity values for the load
--
-- The identity columns are GENERATED ALWAYS, which COPY cannot write to.
-- They are switched to BY DEFAULT for the load and switched back in
-- section 4, with the sequences advanced past the loaded maximum.
-- ---------------------------------------------------------------------
ALTER TABLE customers      ALTER COLUMN customer_id     SET GENERATED BY DEFAULT;
ALTER TABLE accounts       ALTER COLUMN account_id      SET GENERATED BY DEFAULT;
ALTER TABLE transactions   ALTER COLUMN transaction_id  SET GENERATED BY DEFAULT;
ALTER TABLE ledger_entries ALTER COLUMN entry_id        SET GENERATED BY DEFAULT;

-- ---------------------------------------------------------------------
-- 2. Suspend the integrity triggers
-- ---------------------------------------------------------------------
ALTER TABLE ledger_entries DISABLE TRIGGER USER;
ALTER TABLE transactions   DISABLE TRIGGER USER;
ALTER TABLE customers      DISABLE TRIGGER USER;

-- ---------------------------------------------------------------------
-- 3. Load
-- ---------------------------------------------------------------------
\echo '--- loading customers ---'
\copy customers (customer_id, customer_reference, first_name, last_name, email, phone, date_of_birth, kyc_tier, status) FROM 'data/customers.csv' WITH (FORMAT csv, NULL '')

\echo '--- loading accounts ---'
\copy accounts (account_id, account_reference, account_type, customer_id, currency_code, normal_balance, status) FROM 'data/accounts.csv' WITH (FORMAT csv, NULL '')

\echo '--- loading transactions ---'
\copy transactions (transaction_id, transaction_reference, transaction_type, status, channel, currency_code, initiated_by_customer, reverses_transaction, narration, initiated_at, settled_at) FROM 'data/transactions.csv' WITH (FORMAT csv, NULL '')

\echo '--- loading ledger entries ---'
\copy ledger_entries (entry_id, transaction_id, account_id, currency_code, direction, amount, posted_at) FROM 'data/ledger_entries.csv' WITH (FORMAT csv, NULL '')

-- ---------------------------------------------------------------------
-- 4. Restore triggers, identity behaviour and sequence positions
-- ---------------------------------------------------------------------
ALTER TABLE ledger_entries ENABLE TRIGGER USER;
ALTER TABLE transactions   ENABLE TRIGGER USER;
ALTER TABLE customers      ENABLE TRIGGER USER;

-- ENABLE TRIGGER resets ALWAYS triggers to ordinary ENABLED, so the
-- replica-mode protection from Portfolio 1 must be reinstated explicitly.
ALTER TABLE ledger_entries ENABLE ALWAYS TRIGGER trg_ledger_entries_no_update;
ALTER TABLE ledger_entries ENABLE ALWAYS TRIGGER trg_ledger_entries_amount_precision;

SELECT setval(pg_get_serial_sequence('customers','customer_id'),
              (SELECT MAX(customer_id)     FROM customers));
SELECT setval(pg_get_serial_sequence('accounts','account_id'),
              (SELECT MAX(account_id)      FROM accounts));
SELECT setval(pg_get_serial_sequence('transactions','transaction_id'),
              (SELECT MAX(transaction_id)  FROM transactions));
SELECT setval(pg_get_serial_sequence('ledger_entries','entry_id'),
              (SELECT MAX(entry_id)        FROM ledger_entries));

ALTER TABLE customers      ALTER COLUMN customer_id     SET GENERATED ALWAYS;
ALTER TABLE accounts       ALTER COLUMN account_id      SET GENERATED ALWAYS;
ALTER TABLE transactions   ALTER COLUMN transaction_id  SET GENERATED ALWAYS;
ALTER TABLE ledger_entries ALTER COLUMN entry_id        SET GENERATED ALWAYS;

-- ---------------------------------------------------------------------
-- 5. Refresh planner statistics
--
-- Without this the planner works from stale or absent statistics and will
-- make poor choices for reasons unrelated to indexing - which would make
-- every experiment that follows meaningless.
-- ---------------------------------------------------------------------
\echo '--- analysing ---'
VACUUM ANALYZE customers;
VACUUM ANALYZE accounts;
VACUUM ANALYZE transactions;
VACUUM ANALYZE ledger_entries;

-- ---------------------------------------------------------------------
-- 6. Post-load validation
--
-- Every invariant the suspended triggers would have enforced, re-checked
-- across the whole dataset.
-- ---------------------------------------------------------------------
\timing off
\echo ''
\echo '=============================================================='
\echo 'POST-LOAD VALIDATION'
\echo '=============================================================='

\echo ''
\echo 'V1  Row counts'
SELECT 'customers' AS relation, COUNT(*) FROM customers
UNION ALL SELECT 'accounts',       COUNT(*) FROM accounts
UNION ALL SELECT 'transactions',   COUNT(*) FROM transactions
UNION ALL SELECT 'ledger_entries', COUNT(*) FROM ledger_entries
ORDER BY 1;

\echo ''
\echo 'V2  Trial balance per currency - debits must equal credits'
SELECT currency_code,
       SUM(amount) FILTER (WHERE direction = 'DEBIT')  AS total_debits,
       SUM(amount) FILTER (WHERE direction = 'CREDIT') AS total_credits,
       CASE WHEN SUM(CASE WHEN direction='DEBIT' THEN amount ELSE -amount END) = 0
            THEN 'PASS' ELSE 'FAIL' END AS result
FROM ledger_entries GROUP BY currency_code ORDER BY currency_code;

\echo ''
\echo 'V3  Unbalanced transactions (expect 0)'
SELECT COUNT(*) AS unbalanced_transactions FROM (
    SELECT transaction_id
    FROM ledger_entries GROUP BY transaction_id
    HAVING SUM(CASE WHEN direction='DEBIT' THEN amount ELSE -amount END) <> 0
) x;

\echo ''
\echo 'V4  Status vs postings - settled must post >= 2, unsettled must post 0'
SELECT t.status,
       COUNT(*) AS transactions,
       COUNT(*) FILTER (WHERE e.n IS NULL OR e.n = 0) AS with_no_postings,
       COUNT(*) FILTER (WHERE e.n = 1)                AS single_sided,
       CASE
         WHEN t.status IN ('COMPLETED','REVERSED')
              AND COUNT(*) FILTER (WHERE COALESCE(e.n,0) < 2) > 0 THEN 'FAIL'
         WHEN t.status IN ('PENDING','FAILED')
              AND COUNT(*) FILTER (WHERE COALESCE(e.n,0) > 0) > 0 THEN 'FAIL'
         ELSE 'PASS'
       END AS result
FROM transactions t
LEFT JOIN (SELECT transaction_id, COUNT(*) AS n
           FROM ledger_entries GROUP BY transaction_id) e
       ON e.transaction_id = t.transaction_id
GROUP BY t.status ORDER BY t.status;

\echo ''
\echo 'V5  Posting precision vs currency minor_unit (expect 0 violations)'
SELECT COUNT(*) AS precision_violations
FROM ledger_entries le JOIN currencies c USING (currency_code)
WHERE le.amount <> round(le.amount, c.minor_unit);

\echo ''
\echo 'V6  Non-positive postings (expect 0)'
SELECT COUNT(*) AS non_positive_amounts FROM ledger_entries WHERE amount <= 0;

\echo ''
\echo 'V7  Currency mismatches between posting and account (expect 0)'
SELECT COUNT(*) AS currency_mismatches
FROM ledger_entries le JOIN accounts a USING (account_id)
WHERE le.currency_code <> a.currency_code;

\echo ''
\echo 'V8  Append-only protection is active after the load'
SELECT tgname,
       CASE tgenabled WHEN 'O' THEN 'enabled (origin)'
                      WHEN 'A' THEN 'ENABLE ALWAYS'
                      WHEN 'D' THEN 'DISABLED'
                      ELSE tgenabled::text END AS state
FROM pg_trigger
WHERE tgrelid = 'ledger_entries'::regclass AND NOT tgisinternal
ORDER BY tgname;

\echo ''
\echo 'V9  Table and index sizes'
SELECT relname AS relation,
       pg_size_pretty(pg_table_size(c.oid))    AS table_size,
       pg_size_pretty(pg_indexes_size(c.oid))  AS index_size,
       pg_size_pretty(pg_total_relation_size(c.oid)) AS total
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'r'
ORDER BY pg_total_relation_size(c.oid) DESC;

\echo ''
\echo 'V10 Posting distribution across wallets (the skew the benchmark relies on)'
WITH per_wallet AS (
    SELECT account_id, COUNT(*) AS postings
    FROM ledger_entries le
    WHERE EXISTS (SELECT 1 FROM accounts a
                  WHERE a.account_id = le.account_id
                    AND a.account_type = 'CUSTOMER_WALLET')
    GROUP BY account_id
)
SELECT COUNT(*)                                        AS wallets_with_activity,
       MAX(postings)                                   AS busiest,
       ROUND(AVG(postings))                            AS mean,
       PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY postings) AS median,
       PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY postings) AS p99,
       MIN(postings)                                   AS quietest
FROM per_wallet;
